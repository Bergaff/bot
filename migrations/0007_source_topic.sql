-- Рум (топик) форум-чата, из которого пришло сообщение.
--
-- Ссылка на сообщение в форум-чате строится как t.me/<чат>/<рум>/<сообщение>
-- (для приватной супергруппы — t.me/c/<id>/<рум>/<сообщение>). Без id рума
-- ссылка ведёт на весь чат и не открывается: модератор не может найти исходник
-- и переслать его вручную. Поэтому расширение присылает topicId в контракте
-- POST /api/ingest, а мы храним его рядом с source_message_id.
--
-- Колонка необязательная: у каналов и обычных чатов румов нет (NULL).
ALTER TABLE listings ADD COLUMN source_topic_id INTEGER;
